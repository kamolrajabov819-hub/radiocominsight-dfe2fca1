const isLang = (v: unknown): v is Lang => v === "en" || v === "ru" || v === "uz";

/**
 * The choice lives in a cookie rather than localStorage so the server can
 * read it too. If the server rendered English and the client then switched
 * to Russian in an effect, every translated string would fail hydration —
 * and because the provider sits above the data Suspense boundary, its
 * effect lands before the page subtree hydrates, so the mismatch is
 * guaranteed rather than occasional. Reading the same cookie on both sides
 * keeps the two renders identical and removes the flash of English.
 */
export const readLang = createIsomorphicFn()
  .server((): Lang => {
    const v = getCookie(COOKIE);
    return isLang(v) ? v : "en";
  })
  .client((): Lang => {
    const hit = document.cookie.match(/(?:^|;\s*)radiocom-lang=(en|ru|uz)\b/);
    return isLang(hit?.[1]) ? hit[1] : "en";
  });

