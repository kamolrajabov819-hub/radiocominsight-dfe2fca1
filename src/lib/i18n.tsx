/* ------------------------------------------------------------------ *
 * Provider
 * ------------------------------------------------------------------ */

export type Translate = (key: Key, vars?: Record<string, string | number>) => string;

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: Translate;
  /** Translates a metric label that came from the spreadsheet. */
  tMetric: (name: string) => string;
  /** Translates a CRM deal source, including the blank-cell sentinel. */
  tSource: (name: string) => string;
};

const I18nCtx = createContext<Ctx | null>(null);

/** `initial` comes from the cookie, resolved identically on server and client. */
export function LanguageProvider({ initial, children }: { initial: Lang; children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initial);

  const setLang = useCallback((l: Lang) => {
    document.cookie = `${COOKIE}=${l};path=/;max-age=${COOKIE_MAX_AGE};samesite=lax`;
    document.documentElement.lang = l;
    setLangState(l);
  }, []);

  const value = useMemo<Ctx>(() => {
    const table = DICT[lang];
    const t: Translate = (key, vars) => {
      let out = table[key] ?? en[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          out = out.replaceAll(`{${k}}`, String(v));
        }
      }
      return out;
    };
    const tMetric = (name: string) => {
      if (lang === "en") return name;
      return METRICS[name]?.[lang] ?? name;
    };
    const tSource = (name: string) => {
      if (!name || name === UNSPECIFIED_SOURCE) return t("sales.unspecified");
      if (lang === "ru") return name;
      return SOURCES[name]?.[lang] ?? name;
    };
    return { lang, setLang, t, tMetric, tSource };
  }, [lang, setLang]);

  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export function useI18n() {
  const c = useContext(I18nCtx);
  if (!c) throw new Error("useI18n must be inside LanguageProvider");
  return c;
}

/** Segmented EN / RU / UZ control, styled to match the quarter filter. */
export function LanguageToggle() {
  const { lang, setLang, t } = useI18n();
  return (
    <div
      className="flex items-center border border-border"
      role="group"
      aria-label={t("shell.language")}
    >
      {LANGS.map((l) => (
        <button
          key={l.code}
          type="button"
          onClick={() => setLang(l.code)}
          aria-pressed={lang === l.code}
          title={l.label}
          lang={l.code}
          className={
            "border-r border-border px-2 py-1.5 text-xs font-medium transition-colors last:border-r-0 " +
            (lang === l.code
              ? "bg-foreground text-background"
              : "text-muted-foreground hover:bg-surface-sunken hover:text-foreground")
          }
        >
          {l.short}
        </button>
      ))}
    </div>
  );
}
